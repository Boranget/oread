const S2T = new Map();
const T2S = new Map();
for (const p of PAIRS.trim().split(/\s+/)) {
  if (p.length !== 2 || p[0] === p[1]) continue;
  if (!S2T.has(p[0])) S2T.set(p[0], p[1]);
  if (!T2S.has(p[1])) T2S.set(p[1], p[0]);
}

const PH_S2T = PHRASES;
const PH_T2S = PHRASES.map(([s, t]) => [t, s]).sort((a, b) => b[0].length - a[0].length);

export const zhLabels = { off: '原文', s: '简体', t: '繁体' };

// mode: 'off' | 's' | 't'
export function convertZh(text, mode) {
  if (!text || mode === 'off') return text;
  const phrases = mode === 't' ? PH_S2T : PH_T2S;
  const map = mode === 't' ? S2T : T2S;
  let out = text;
  for (const [a, b] of phrases) {
    if (out.indexOf(a) !== -1) out = out.split(a).join(b);
  }
  let res = '';
  for (const ch of out) res += map.get(ch) || ch;
  return res;
}
